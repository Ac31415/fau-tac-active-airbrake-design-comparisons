%% build_simulink_model.m
% Programmatically constructs and wires the complete 3D 6-DOF Active Airbrake Simulink Model:
%   "Rocket_Active_Airbrake_6DOF.slx"
%
% Features:
%   - Full 3D 6-DOF Quaternion Equations of Motion & Atmospheric/Gravity Modeling
%   - Teensy 4.1 Flight Computer GNC (Discrete Kalman Filter, Apogee Predictor, Discrete PID)
%   - Realistic Actuator Electronics (Savox SC-1258TG Servo vs Actuonix L16 Linear Actuator, LiPo battery sag)
%   - Dual Airbrake Designs (Downward Hinged Flaps 0-90 deg vs Radially Outward Sliding Flaps at 90 deg)
%   - Fully connected signals, scopes, and logging outports
%
% Copyright (c) 2026 Aerospace Systems Laboratory

clear; clc;
proj_root = fileparts(fileparts(mfilename('fullpath')));
if isempty(proj_root), proj_root = pwd; end
addpath(fullfile(proj_root, 'scripts'));
addpath(fullfile(proj_root, 'functions'));
addpath(fullfile(proj_root, 'models'));

init_airbrake_params;

model_name = 'Rocket_Active_Airbrake_6DOF';
model_path = fullfile(proj_root, 'models', [model_name, '.slx']);

% Close if already open
if bdIsLoaded(model_name)
    close_system(model_name, 0);
end

fprintf('==> Constructing Simulink model: %s...\n', model_name);
new_system(model_name);
open_system(model_name);

% Configure Solver Settings
set_param(model_name, 'Solver', 'ode4'); % Runge-Kutta 4th Order
set_param(model_name, 'FixedStep', '0.002'); % 500 Hz continuous plant
set_param(model_name, 'StopTime', '28.0');
set_param(model_name, 'SaveTime', 'on');
set_param(model_name, 'SaveOutput', 'on');
set_param(model_name, 'SignalLogging', 'on');
set_param(model_name, 'SignalLoggingName', 'logsout');

% Set PreLoadFcn to automatically run parameter initialization
set_param(model_name, 'PreLoadFcn', 'init_airbrake_params');

