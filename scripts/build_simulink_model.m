'    else\n' ...
'        pid_I = tent_I;\n' ...
'        u_pid = tent_u;\n' ...
'    end\n' ...
'    \n' ...
'    du = max(-3.0*dt, min(3.0*dt, u_pid - u_prev));\n' ...
